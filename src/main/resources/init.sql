    select old_area.id
    from fm_basic_dictionaries old_area
    join fm_basic_dictionaries new_area on new_area.code = substring(old_area.code from 6)
    where old_area.code like 'AREA\_%' escape '\'
),
duplicate_area_tree as (
    select id
    from duplicate_area_roots
    union all
    select child.id
    from fm_basic_dictionaries child
    join duplicate_area_tree parent on child.parent_id = parent.id
)
delete from fm_basic_dictionaries
where id in (select id from duplicate_area_tree);

