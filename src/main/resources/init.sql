create table if not exists fm_users (
    id bigint generated by default as identity primary key,
    created_time timestamp with time zone not null default now(),
    modify_time timestamp with time zone not null default now(),
    username varchar(80) not null,
    real_name varchar(120) not null,
    password_hash varchar(255) not null,
    department varchar(80),
    organization_code varchar(80) not null default 'ORGANIZATION_RATEL',
    position varchar(80),
    identity_no varchar(40),
    phone varchar(40),
    email varchar(120),
    avatar_url varchar(300),
    avatar_base64 text,
    enabled boolean not null default true,
    constraint uk_fm_users_company_username unique (organization_code, username),
    constraint uk_fm_users_company_identity_no unique (organization_code, identity_no)
);

